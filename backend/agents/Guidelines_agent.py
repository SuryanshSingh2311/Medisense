import os
import logging
from typing import Dict, Any
from pydantic import BaseModel, Field
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.messages import SystemMessage, HumanMessage
from langchain_openrouter import ChatOpenRouter
from config import settings
from fastmcp import Client
from fastmcp.exceptions import ToolError

# -------------------------------------------------------------------------
# 1. Logging Configuration
# -------------------------------------------------------------------------
logger = logging.getLogger("Medisense.GuidelinesAgent")
logger.setLevel(logging.INFO)
if not logger.handlers:
    ch = logging.StreamHandler()
    ch.setFormatter(logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s'))
    logger.addHandler(ch)

# -------------------------------------------------------------------------
# 2. Schema Definitions
# -------------------------------------------------------------------------
class QueryGeneration(BaseModel):
    """Structured search query generated by the LLM based on patient state."""
    clinical_summary: str = Field(
        description="A concise 1-sentence summary of the patient's cancer profile (e.g., 'Stage IV NSCLC, KRAS G12C positive, High Grade')."
    )
    vector_search_query: str = Field(
        description="Optimized keywords for vector database retrieval (e.g., 'First-line therapy Stage IV NSCLC KRAS G12C')."
    )

class GuidelinesData(BaseModel):
    """The final payload stored in the graph state."""
    clinical_summary: str
    nccn_retrieval: str
    esmo_retrieval: str
    retrieval_successful: bool

# -------------------------------------------------------------------------
# 3. Model Configuration (OpenRouter)
# -------------------------------------------------------------------------
def get_openrouter_llm():
    api_key = settings.openrouter_api_key or os.getenv("OPENROUTER_API_KEY")
    if not api_key:
        raise ValueError("OPENROUTER_API_KEY environment variable is not set in .env")

    return ChatOpenRouter(
        model=settings.model_id, 
        api_key=api_key,
        temperature=0.0,
        max_retries=3
    )

GUIDELINES_SYSTEM_PROMPT = """You are an expert oncology clinical librarian.
Your task is to analyze a patient's parsed diagnostic data (Pathology, Radiology, Genomics) 
and generate a highly optimized search query to retrieve treatment protocols from NCCN and ESMO databases.

RULES:
1. Synthesize the data into a single `clinical_summary`.
2. Generate a precise `vector_search_query` focusing on cancer type, stage, and actionable biomarkers.
3. Format output strictly as JSON.
"""

# -------------------------------------------------------------------------
# 4. FastMCP Tool Execution Helper
# -------------------------------------------------------------------------
async def fetch_guidelines_via_mcp(query: str, source: str) -> str:
    mcp_server_url = settings.fastmcp_rag_server
    
    try:
        async with Client(mcp_server_url, mode="auto") as client:
            tool_name = "search_nccn" if source == "NCCN" else "search_esmo"
            logger.info(f"Calling MCP Tool '{tool_name}' with query: {query}")
            
            result = await client.call_tool(tool_name, {"query": query, "top_k": 3})
            
            if result.data is not None:
                return str(result.data)
            return "No relevant guidelines retrieved from vector database."
            
    except ToolError as e:
        logger.error(f"MCP Tool execution failed for {source}: {str(e)}")
        return f"Tool Error: {str(e)}"
    except Exception as e:
        logger.error(f"FastMCP connection failed: Is the server running at {mcp_server_url}? Error: {str(e)}")
        return "Connection to Vector DB Microservice failed."

# -------------------------------------------------------------------------
# 5. Core Agent Node Function (Async)
# -------------------------------------------------------------------------
async def run_guidelines_agent(state: Dict[str, Any]) -> Dict[str, Any]:
    logger.info("Initializing Guidelines Agent...")
    
    pathology = state.get("pathology_data", {})
    radiology = state.get("radiology_data", {})
    genomics = state.get("genomics_data", {})
    
    patient_context = f"""
    PATHOLOGY: {pathology.get('histology_type', 'Unknown')}, Grade: {pathology.get('tumor_grade', 'Unknown')}
    RADIOLOGY: Stage: {radiology.get('clinical_staging', 'Unknown')}, Primary: {radiology.get('primary_mass_location', 'Unknown')}
    GENOMICS: EGFR: {genomics.get('egfr_status', 'Unknown')}, KRAS: {genomics.get('kras_status', 'Unknown')}, PD-L1: {genomics.get('pd_l1_expression', 'Unknown')}
    """

    try:
        # FIXED: Use correct openrouter loader function
        llm = get_openrouter_llm()
        structured_llm = llm.with_structured_output(QueryGeneration)
        
        prompt = ChatPromptTemplate.from_messages([
            SystemMessage(content=GUIDELINES_SYSTEM_PROMPT),
            HumanMessage(content=f"PATIENT CONTEXT:\n{patient_context}")
        ])
        
        query_chain = prompt | structured_llm
        logger.info("Generating optimized vector search query via OpenRouter...")
        query_result: QueryGeneration = query_chain.invoke({})
        
    except Exception as e:
        logger.error(f"Failed to generate query: {str(e)}")
        fallback_data = GuidelinesData(
            clinical_summary="Error generating summary.",
            nccn_retrieval="Search failed.",
            esmo_retrieval="Search failed.",
            retrieval_successful=False
        )
        return {"guidelines_data": fallback_data.model_dump()}

    logger.info(f"Query generated: '{query_result.vector_search_query}'")
    
    nccn_results = await fetch_guidelines_via_mcp(query_result.vector_search_query, "NCCN")
    esmo_results = await fetch_guidelines_via_mcp(query_result.vector_search_query, "ESMO")

    final_data = GuidelinesData(
        clinical_summary=query_result.clinical_summary,
        nccn_retrieval=nccn_results,
        esmo_retrieval=esmo_results,
        retrieval_successful=True if "Connection to Vector DB" not in nccn_results else False
    )
    
    logger.info("Guidelines retrieval complete.")
    return {"guidelines_data": final_data.model_dump()}