from typing import Dict, Any, List, TypedDict, Optional
from pydantic import BaseModel, Field

# ============================================================================
# 1. GLOBAL LANGGRAPH STATE
# ============================================================================
class TumorBoardState(TypedDict):
    """
    The central state object passed between all LangGraph nodes.
    Each agent reads from this state and returns a dictionary to update its respective keys.
    """
    # --- Raw Inputs (Populated by FastAPI gateway) ---
    raw_pathology_report: str
    raw_radiology_report: str
    raw_genomics_report: str
    patient_labs: Dict[str, Any]

    # --- Tier 1: Extracted Diagnostic Data ---
    pathology_data: Dict[str, Any]
    radiology_data: Dict[str, Any]
    genomics_data: Dict[str, Any]
    
    # --- Tier 2: Synthesized Data ---
    guidelines_data: Dict[str, Any]
    treatment_plan: Dict[str, Any]
    
    # --- Tier 3: Safety & Governance ---
    pharmacology_data: Dict[str, Any]
    moderator_data: Dict[str, Any]
    
    # --- Control Flags ---
    consensus_reached: bool
    retry_count: int


# ============================================================================
# 2. AGENT OUTPUT SCHEMAS (Pydantic Models for LLM Structured Output)
# ============================================================================

class PathologyExtraction(BaseModel):
    """Structured data extracted from an unstructured pathology report."""
    histology_type: str = Field(
        description="The histological classification of the tumor (e.g., Adenocarcinoma, Squamous Cell Carcinoma). Output 'Not Specified' if absent."
    )
    tumor_grade: str = Field(
        description="The differentiation grade of the tumor (e.g., G1, G2, G3, High Grade). Output 'Not Specified' if absent."
    )
    biopsy_findings: str = Field(
        description="Concise summary of critical biopsy findings, surgical margins, and lymph node involvement."
    )
    extraction_successful: bool = Field(
        default=True,
        description="Internal flag. True if data was successfully extracted, False if fallback was triggered."
    )


class RadiologyExtraction(BaseModel):
    """Structured data extracted from an unstructured imaging or radiology report."""
    imaging_modality: str = Field(
        description="The type of scan performed (e.g., Contrast CT Chest, MRI Abdomen, PET-CT). Output 'Not Specified' if absent."
    )
    primary_mass_location: str = Field(
        description="The anatomical location of the primary tumor/lesion. Output 'Not Specified' if absent."
    )
    lesion_dimensions: str = Field(
        description="The size or dimensions of the primary mass (e.g., '3.2 x 2.8 cm'). Output 'Not Specified' if absent."
    )
    metastasis_sites: List[str] = Field(
        description="A list of anatomical sites where metastatic spread is identified. Output an empty list [] if no metastasis is noted."
    )
    clinical_staging: str = Field(
        description="The clinical stage or TNM staging if mentioned in the impression (e.g., 'cT2N1M0' or 'Stage IIB'). Output 'Not Specified' if absent."
    )
    extraction_successful: bool = Field(
        default=True,
        description="Internal flag. True if data was successfully extracted."
    )


class GenomicsExtraction(BaseModel):
    """Structured data extracted from genomic/molecular biomarker reports."""
    egfr_status: str = Field(
        description="EGFR mutation status (e.g., 'Positive - Exon 19 Deletion', 'Negative', 'Not Specified')."
    )
    alk_status: str = Field(
        description="ALK rearrangement status (e.g., 'Positive', 'Negative', 'Not Specified')."
    )
    kras_status: str = Field(
        description="KRAS mutation status, specifically noting variants like G12C if present. Output 'Not Specified' if absent."
    )
    pd_l1_expression: str = Field(
        description="PD-L1 Tumor Proportion Score (TPS) percentage (e.g., '<1%', '1-49%', '>=50%'). Output 'Not Specified' if absent."
    )
    other_biomarkers: List[str] = Field(
        description="List of any other detected actionable mutations or fusions. Empty list [] if none."
    )
    extraction_successful: bool = Field(
        default=True,
        description="Internal flag. True if data was successfully extracted."
    )


class GuidelinesQueryGeneration(BaseModel):
    """Intermediate schema used by the Guidelines Agent to formulate the Vector DB query."""
    clinical_summary: str = Field(
        description="A concise 1-sentence summary of the patient's cancer profile."
    )
    vector_search_query: str = Field(
        description="Optimized keywords for vector database retrieval."
    )


class GuidelinesData(BaseModel):
    """Final payload generated by the Guidelines Agent and stored in the graph state."""
    clinical_summary: str
    nccn_retrieval: str
    esmo_retrieval: str
    retrieval_successful: bool


class OncologyDraft(BaseModel):
    """Structured oncology treatment plan drafted by the LLM."""
    primary_diagnosis_summary: str = Field(
        description="A comprehensive summary of the patient's cancer profile."
    )
    recommended_regimen: str = Field(
        description="The primary recommended treatment protocol (drugs, dosing, and schedule) based on guidelines."
    )
    alternative_regimen: str = Field(
        description="A secondary alternative treatment regimen in case of contraindications or patient intolerance."
    )
    clinical_rationale: str = Field(
        description="A clear medical justification for the chosen regimen, directly referencing the patient's biomarkers and staging."
    )
    guideline_citations: List[str] = Field(
        description="Specific snippets or references from the retrieved NCCN/ESMO guidelines supporting this decision."
    )
    drafting_successful: bool = Field(
        default=True,
        description="Internal flag. True if plan was successfully drafted."
    )


class PharmacologyEvaluation(BaseModel):
    """Structured safety evaluation of the proposed oncology regimen."""
    is_safe: bool = Field(
        description="True if the regimen is safe. False if critical contraindications, toxicities, or interactions are detected."
    )
    identified_risks: List[str] = Field(
        description="Specific safety risks detected. Empty list if safe."
    )
    pharmacology_notes: str = Field(
        description="A clear clinical explanation of the safety evaluation and any physiological bottlenecks."
    )
    recommended_modifications: str = Field(
        description="Actionable advice for the Oncology Agent to adjust the plan. Output 'None required' if safe."
    )
    evaluation_successful: bool = Field(
        default=True,
        description="Internal flag. True if evaluation ran successfully."
    )


class ModeratorDirective(BaseModel):
    """Structured directives issued to the Oncology Agent for plan renegotiation."""
    conflict_summary: str = Field(
        description="A concise summary of why the previous plan was rejected by the Pharmacology Agent."
    )
    mandatory_adjustments: str = Field(
        description="Strict clinical instructions for the Oncology Agent on how to revise the regimen."
    )
    moderation_successful: bool = Field(
        default=True,
        description="Internal flag. True if directive was successfully generated."
    )